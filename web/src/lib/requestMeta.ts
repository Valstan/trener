// IP и user-agent запроса — для журнальных записей подписей (D-016).
//
// Аудит #057 (векторы a, c, f): брался ПЕРВЫЙ элемент x-forwarded-for, то есть
// значение, полностью контролируемое клиентом. nginx в режиме $proxy_add_x_forwarded_for
// дописывает реальный адрес ПОСЛЕ клиентского значения, поэтому подделанный адрес
// оказывался первым и попадал в `legal-signatures.ip` — в запись, которую проект сам
// называет неизменяемым доказательным журналом 152-ФЗ.
//
// Берём ПОСЛЕДНИЙ непустой элемент цепочки: это значение добавил наш прокси. Если
// цепочки нет (прямой заход, стенд, прод-приёмка по loopback) — падаем на x-real-ip и
// дальше на честное «неизвестно», но НЕ на клиентский заголовок.
//
// Оговорка, которую важно не потерять: подделать заголовок всё ещё можно, если запрос
// дойдёт до приложения мимо nginx. На проде это невозможно — приложение слушает только
// 127.0.0.1, наружу отдан только прокси (deploy/systemd/trener.service). Поэтому
// корректность здесь опирается на «единственный путь — наш прокси», а не на заголовок.
export const clientMeta = (req: Request): { ip: string; userAgent: string } => {
  const chain = (req.headers.get('x-forwarded-for') ?? '')
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean)
  // Реальный адрес — тот, что ближе к серверу (дописан прокси).
  const ip = chain.length
    ? (chain[chain.length - 1] ?? '')
    : (req.headers.get('x-real-ip') ?? '').trim()
  const userAgent = (req.headers.get('user-agent') ?? '').slice(0, 512)
  return { ip: ip.slice(0, 64), userAgent }
}
