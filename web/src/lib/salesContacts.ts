// Контакты для покупателя платформы — секция «Подключить свою школу» на лендинге.
//
// Решение владельца 2026-08-01: публикуем все пять каналов, чтобы директор школы
// написал в привычный ему. Значения ПУБЛИЧНЫЕ (страница показывает их всем) и
// принадлежат продавцу платформы, а не филиалу, поэтому живут в репо рядом с
// остальными точками входа экосистемы (ecosystem.ts) — секретами они не являются.
//
// href === null → пункт рендерится текстом. У MAX идентификатор — номер телефона,
// а ссылочную схему профиля владелец не давал; выдумывать URL нельзя (мёртвая
// ссылка хуже её отсутствия — тот же довод, что и у подписи автора).

export type SalesContact = {
  /** Эмодзи-иконка канала; в разметке помечается aria-hidden. */
  ic: string
  /** Название канала — что читает глазами директор школы. */
  label: string
  /** Человекочитаемое значение: @ник, номер, адрес. */
  value: string
  /** Куда ведёт клик; null — канал показываем без ссылки. */
  href: string | null
}

