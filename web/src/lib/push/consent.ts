import type { Payload } from 'payload'

// Пуш родителю после отзыва согласия — аудит #057, вектор (f), high.
//
// Суть находки: `sendPushToUser` глушила ТОЛЬКО демо-адресата. Ни один путь отправки
// не смотрел `consents`, поэтому родитель, отозвавший согласие (или ещё не давший
// его), продолжал получать «тренировка перенесена», «подтвердите участие», «новое
// объявление» — то есть обработку ПДн ребёнка продолжалась после отзыва. 152-ФЗ
// ст. 9: после отзыва обработка должна быть прекращена.
//
// ПОЧЕМУ фильтр здесь, в шлюзе, а не в вызывающих путях: отправка идёт из 13 мест
// (фан-ауты объявлений/расписания/матчей/вопросов/платежей, cron-напоминания, ответ
// тренеру), и «починить четыре пути» — это гарантия, что седьмой не забыли. Гейт на
// согласие держится в `sendPushToUser`, где адресат известен всегда.
//
// ПОЧЕМУ это не про «роли родителя вообще»: согласие — про ПДн ребёнка, поэтому
// фильтр касается только адресата-родителя. Тренер, админ и владелец получают пуши
// как сотрудники/контрагенты, их правовое основание — не родительское согласие, и
// их отзыв согласия одним из детей не должен глушить рабочие уведомления.
//
// Граница решения (осознанный компромисс, а не «недостающая деталь»): блокируется
// ЛЮБОЙ пуш родителю без активного согласия, включая сообщения о его собственной
// заявке и переписку по вопросу тренеру. Альтернатива — флаг «это про ПДн ребёнка»
// в `PushMessage` и адресный обход с возвратом вопросов-ответов; она юридически
// тоньше, но оставляет обработку включённой там, где решение «после отзыва ничего не
// отправляем» должно быть абсолютным. Вернуть адресность — одна строка здесь плюс
// флаг в сборщиках сообщений.

// Предикат без БД: consentGiven-true согласие должно существовать. Нулевое число —
// и отозванное (строки удаляются), и ещё не данное; оба состояния означают, что
// пуш про ПДн ребёнка отправлять нельзя.
export const pushAllowedByConsent = (i: { parent: boolean; consentsCount: number }): boolean =>
  !i.parent || i.consentsCount > 0

export const countActiveConsents = async (payload: Payload, parentId: number | string): Promise<number> => {
  const res = await payload.count({
    collection: 'consents',
    where: { and: [{ parent: { equals: parentId } }, { consentGiven: { equals: true } }] },
    overrideAccess: true,
  })
  return res.totalDocs
}